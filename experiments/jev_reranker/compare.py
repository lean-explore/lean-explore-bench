"""Compare Qwen3-Reranker and Jev on the same candidate pools.

Every system reorders the same pool, so differences come from the reranker alone.
"neural only" sorts by the reranker's score; "production mix" puts that score into
LeanExplore's final-score formula (min-max normalized reranker score plus the BM25,
dependency and fuzzy-name terms recorded by dump_pools.py). Ties keep pool order.
Autogenerated declarations are dropped from the ranking, as the engine does.
"""

import argparse
import json
import math
import random
from collections import defaultdict
from pathlib import Path

EPSILON = 1e-10
QWEN = "Qwen3-Reranker-0.6B as deployed"
DEPTH = 10


def normalize(scores: list[float]) -> list[float]:
    """Min-max normalize, as lean_explore.search.scoring.normalize_scores does."""
    low, high = min(scores), max(scores)
    if high - low < EPSILON:
        return [1.0 if high > EPSILON else 0.0] * len(scores)
    return [(score - low) / (high - low) for score in scores]


def ranking(candidates: list[dict], scores: list[float]) -> list[str]:
    order = sorted(range(len(candidates)), key=lambda i: -scores[i])
    return [
        candidates[i]["name"] for i in order if not candidates[i]["autogenerated"]
    ]


def metrics(ranked: list[str], judgments: dict[str, int]) -> dict[str, float]:
    best = max(judgments.values())
    targets = {name for name, grade in judgments.items() if grade == best}
    rank = next((r for r, name in enumerate(ranked, 1) if name in targets), None)
    gain = sum(
        (2 ** judgments.get(name, 0) - 1) / math.log2(position + 1)
        for position, name in enumerate(ranked[:DEPTH], 1)
    )
    ideal = sum(
        (2**grade - 1) / math.log2(position + 1)
        for position, grade in enumerate(
            sorted(judgments.values(), reverse=True)[:DEPTH], 1
        )
    )
    return {
        "hit@1": float(rank == 1),
        "hit@5": float(rank is not None and rank <= 5),
        "mrr@10": 1 / rank if rank and rank <= DEPTH else 0.0,
        "ndcg@10": gain / ideal,
    }


def mean(values: list[float]) -> float:
    return sum(values) / len(values)


def paired(a: list[float], b: list[float], rounds: int = 10000) -> str:
    """Mean of a minus b with a 95% paired-bootstrap interval, and win counts."""
    deltas = [x - y for x, y in zip(a, b)]
    rng = random.Random(0)
    means = sorted(mean(rng.choices(deltas, k=len(deltas))) for _ in range(rounds))
    low, high = means[int(0.025 * rounds)], means[int(0.975 * rounds)]
    wins = sum(d > EPSILON for d in deltas)
    losses = sum(d < -EPSILON for d in deltas)
    return (
        f"{mean(deltas):+.3f} [{low:+.3f}, {high:+.3f}], "
        f"better on {wins}, worse on {losses}, equal on {len(deltas) - wins - losses}"
    )


def table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("| --- |" + " ---: |" * (len(headers) - 1))
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pools", required=True)
    parser.add_argument("--jev", nargs="+", required=True, help="jev_scores.py outputs")
    parser.add_argument("--extra", nargs="*", default=[], metavar="LABEL=PATH",
                        help="other score files, such as qwen_official.py outputs")
    args = parser.parse_args()

    pools = {}
    for line in Path(args.pools).read_text().splitlines():
        record = json.loads(line)
        pools[record["id"]] = record
    jev: dict[str, dict[str, dict]] = {}
    for path in args.jev:
        rows = [json.loads(line) for line in Path(path).read_text().splitlines()]
        jev[rows[0]["mode"]] = {row["id"]: row for row in rows}
    extra: dict[str, dict[str, list[float]]] = {}
    for item in args.extra:
        label, path = item.split("=", 1)
        rows = [json.loads(line) for line in Path(path).read_text().splitlines()]
        extra[label] = {row["id"]: row["scores"] for row in rows}
    ids = [
        i for i in pools if all(i in rows for rows in [*jev.values(), *extra.values()])
    ]

    results: dict[str, dict[str, dict[str, float]]] = defaultdict(dict)
    in_pool = {}
    for query_id in ids:
        record = pools[query_id]
        candidates, judgments = record["candidates"], record["judgments"]
        rest = [c["rest"] for c in candidates]
        best = max(judgments.values())
        in_pool[query_id] = any(
            judgments.get(c["name"]) == best and not c["autogenerated"]
            for c in candidates
        )
        neural = {QWEN: [c["qwen"] for c in candidates]}
        for label, scores_by_id in extra.items():
            neural[label] = scores_by_id[query_id]
        for mode, rows in jev.items():
            neural[f"Jev {mode}"] = rows[query_id]["scores"]
        systems = {"Retrieval order (no reranker)": [-i for i in range(len(candidates))]}
        for name, scores in neural.items():
            systems[f"{name}, neural only"] = scores
        for name, scores in neural.items():
            systems[f"{name}, production mix"] = [
                n + r for n, r in zip(normalize(scores), rest)
            ]
        for name, scores in systems.items():
            results[name][query_id] = metrics(ranking(candidates, scores), judgments)

    names = ["hit@1", "hit@5", "mrr@10", "ndcg@10"]
    found = sum(in_pool.values())
    print(f"Queries: {len(ids)}. Best-grade target in the pool: {found} "
          f"({found / len(ids):.1%}); no reranker can exceed that hit rate.\n")
    print(table(["System", *names], [
        [system, *(f"{mean([m[n] for m in per.values()]):.3f}" for n in names)]
        for system, per in results.items()
    ]))

    types = sorted({pools[i]["query_type"] for i in ids})
    print("\nnDCG@10 by query type\n")
    print(table(["System", *types], [
        [system, *(
            f"{mean([per[i]['ndcg@10'] for i in ids if pools[i]['query_type'] == t]):.3f}"
            for t in types
        )]
        for system, per in results.items()
    ]))

    print("\nPaired differences in nDCG@10 (mean, 95% bootstrap interval)\n")
    challengers = [f"Jev {mode}" for mode in jev]
    for baseline in [QWEN, *extra]:
        for challenger in [*extra, *challengers]:
            if challenger == baseline or (baseline != QWEN and challenger in extra):
                continue
            for setting in ("neural only", "production mix"):
                a = results[f"{challenger}, {setting}"]
                b = results[f"{baseline}, {setting}"]
                print(f"- {challenger} minus {baseline}, {setting}: "
                      f"{paired([a[i]['ndcg@10'] for i in ids], [b[i]['ndcg@10'] for i in ids])}")

    print("\nCost and latency per query (pool of "
          f"{round(mean([len(pools[i]['candidates']) for i in ids]))} candidates)\n")
    qwen_ms = sorted(pools[i]["qwen_ms"] for i in ids)
    print(f"- Qwen3-Reranker-0.6B on one H100, as deployed: median {qwen_ms[len(qwen_ms) // 2]:.0f} ms")
    for mode, rows in jev.items():
        seconds = sorted(rows[i]["seconds"] for i in ids)
        print(f"- Jev {mode}: median {seconds[len(seconds) // 2]:.2f} s wall clock, "
              f"{mean([rows[i]['requests'] for i in ids]):.0f} requests, "
              f"{mean([rows[i]['input_tokens'] for i in ids]):.0f} input tokens, "
              f"${mean([rows[i]['cost'] for i in ids]):.5f}")


if __name__ == "__main__":
    main()
