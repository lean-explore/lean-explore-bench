"""Dump the candidate pools LeanExplore reranks, with Qwen3-Reranker scores.

Runs inside a LeanExplore checkout's environment (it needs a GPU for sensible speed).
For each query it repeats the engine's retrieval steps, takes the pool the reranker
would see, scores it with the production reranker settings and records, per candidate,
the reranker score and the rest of the production final score (BM25 over the
informalization, dependency count, fuzzy name match). That lets another reranker's
scores be swapped into the same final-score formula offline.
"""

import argparse
import asyncio
import json
import time
from pathlib import Path

from lean_explore.search.engine import SearchEngine
from lean_explore.search.ranking import (
    DEFAULT_RERANK_WEIGHTS,
    DEPENDENCY_BOOST_POOL_SIZE,
    apply_dependency_boost,
    combine_rerank_scores,
    fuse_rankings,
    rerank_document,
)
from lean_explore.search.scoring import normalize_scores
from lean_explore.search.tokenization import is_autogenerated

RETRIEVAL_K = 1000  # the engine's default faiss_k and bm25_k
CHECKED_QUERIES = 10  # how many pools are checked against engine.search()


async def dump(args: argparse.Namespace) -> None:
    data = Path(args.data_directory)
    engine = SearchEngine(
        db_url=f"sqlite+aiosqlite:///{data / 'lean_explore.db'}", data_directory=data
    )
    queries = [json.loads(line) for line in Path(args.queries).read_text().splitlines()]
    with Path(args.output).open("x") as out:
        for number, item in enumerate(queries):
            query = item["query"]
            started = time.perf_counter()
            name_scores = engine.indexes.name_candidates(query, RETRIEVAL_K)
            semantic_scores = await engine._semantic_candidates(query, RETRIEVAL_K)
            fused = fuse_rankings(name_scores, semantic_scores)
            declarations = await engine._load_declarations(
                [cid for cid, _ in fused[:DEPENDENCY_BOOST_POOL_SIZE]]
            )
            boosted = apply_dependency_boost(fused, declarations)
            pool = [
                declarations[cid]
                for cid, _ in boosted[: args.pool]
                if cid in declarations
            ]
            retrieved = time.perf_counter()
            documents = [rerank_document(d) for d in pool]
            qwen = (await engine.reranker_client.rerank(query, documents)).scores
            reranked = time.perf_counter()
            final = combine_rerank_scores(query, pool, qwen)
            normalized = normalize_scores(qwen)
            rest = [
                score - DEFAULT_RERANK_WEIGHTS.reranker * norm
                for score, norm in zip(final, normalized)
            ]

            if number < CHECKED_QUERIES:
                ours = [
                    d.name
                    for d, _ in sorted(zip(pool, final), key=lambda p: p[1], reverse=True)
                    if not is_autogenerated(d.name)
                ][:10]
                theirs = await engine.search(query, limit=10, rerank_top=args.pool)
                assert ours == [r.name for r in theirs], (item["id"], ours, theirs)

            record = {
                **item,
                "retrieval_ms": round(1000 * (retrieved - started), 1),
                "qwen_ms": round(1000 * (reranked - retrieved), 1),
                "candidates": [
                    {
                        "name": d.name,
                        "document": document,
                        "autogenerated": is_autogenerated(d.name),
                        "qwen": q,
                        "rest": r,
                    }
                    for d, document, q, r in zip(pool, documents, qwen, rest)
                ],
            }
            out.write(json.dumps(record, ensure_ascii=False) + "\n")
            out.flush()
            print(f"{number + 1}/{len(queries)} {item['id']}", flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-directory", required=True)
    parser.add_argument("--queries", required=True, help="JSON lines of mix queries")
    parser.add_argument("--output", required=True)
    parser.add_argument("--pool", type=int, default=50, help="reranking depth")
    asyncio.run(dump(parser.parse_args()))
