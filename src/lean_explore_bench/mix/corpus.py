"""Read a LeanExplore corpus snapshot and pick declarations worth querying.

A snapshot is the SQLite file LeanExplore publishes (``lean_explore.db``),
with one row per declaration. Many rows are generated by Lean rather than
written by a person: structure fields, ``simps`` lemmas, ``ext_iff`` and the
like. Their ``source_text`` is the parent declaration, so they make poor
benchmark targets. A declaration is *eligible* only when its own source
introduces it by name.
"""

import hashlib
import re
import sqlite3
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

LIBRARY_OF_ROOT = {
    "Mathlib": "mathlib",
    "Init": "core",
    "Std": "core",
    "Batteries": "core",
    "Physlib": "physlib",
    "PhysLean": "physlib",
    "QuantumInfo": "quantuminfo",
    "Cslib": "cslib",
    "FLT": "flt",
    "FormalConjectures": "formal-conjectures",
    "FormalConjecturesForMathlib": "formal-conjectures",
}
"""Module root to library key. Roots not listed (``Lean``) are skipped."""

EXCLUDED_AREAS = frozenset(
    {
        "Deprecated",
        "Do",
        "Grind",
        "Init",
        "Internal",
        "Lean",
        "Mathport",
        "Omega",
        "Recycling",
        "Sat",
        "Slop",
        "Std",
        "Tactic",
        "Testing",
        "Util",
    }
)
"""Second module components that hold tooling, internals or scratch work."""

KIND_OF_KEYWORD = {
    "theorem": "theorem",
    "lemma": "theorem",
    "def": "definition",
    "abbrev": "definition",
    "structure": "structure",
    "class": "structure",
    "inductive": "structure",
}

MIN_SOURCE_CHARS = 40
MAX_SOURCE_CHARS = 4000

_COMMENT = re.compile(r"/-.*?-/", re.DOTALL)
_HEADER = re.compile(
    r"\b(theorem|lemma|def|abbrev|structure|class|inductive)\s+([^\s:({\[]+)"
)


@dataclass(frozen=True)
class Declaration:
    """One eligible declaration.

    Attributes:
        name: Fully qualified Lean name.
        module: Module that contains it.
        library: Library key, for example ``mathlib`` or ``physlib``.
        area: Second module component, for example ``Algebra``.
        kind: ``theorem``, ``definition`` or ``structure``.
        docstring: Docstring from the source, if any.
        source_text: Source of the declaration.
        informalization: LeanExplore's natural-language description, if any.
    """

    name: str
    module: str
    library: str
    area: str
    kind: str
    docstring: str | None
    source_text: str
    informalization: str | None


def library_and_area(module: str) -> tuple[str, str] | None:
    """Return the library key and area of a module, or None when skipped."""
    parts = module.split(".")
    library = LIBRARY_OF_ROOT.get(parts[0])
    if library is None:
        return None
    area = parts[1] if len(parts) > 1 else "root"
    if area in EXCLUDED_AREAS or {"Deprecated", "Internal"} & set(parts):
        return None
    return library, area


def declared_kind(name: str, source_text: str) -> str | None:
    """Return the kind when ``source_text`` introduces ``name`` itself.

    The first declaration keyword after comments must be followed by a name
    that is ``name`` or a dotted suffix of it. Generated declarations fail
    this test because their source is the parent declaration.
    """
    match = _HEADER.search(_COMMENT.sub(" ", source_text))
    if match is None:
        return None
    declared = match.group(2).removeprefix("_root_.")
    if name != declared and not name.endswith("." + declared):
        return None
    return KIND_OF_KEYWORD[match.group(1)]


def to_declaration(
    name: str,
    module: str,
    docstring: str | None,
    source_text: str,
    informalization: str | None,
) -> Declaration | None:
    """Build a :class:`Declaration` from a corpus row, or None if ineligible."""
    placed = library_and_area(module)
    if placed is None:
        return None
    if not MIN_SOURCE_CHARS <= len(source_text) <= MAX_SOURCE_CHARS:
        return None
    if "@[deprecated" in source_text:
        return None
    kind = declared_kind(name, source_text)
    if kind is None:
        return None
    return Declaration(
        name=name,
        module=module,
        library=placed[0],
        area=placed[1],
        kind=kind,
        docstring=docstring or None,
        source_text=source_text,
        informalization=informalization or None,
    )


@dataclass(frozen=True)
class Corpus:
    """A corpus snapshot.

    Attributes:
        revision: Identifier that pins the snapshot: its label and a hash of
            every declaration name.
        names: Every declaration name in the snapshot, eligible or not.
        eligible: Declarations that can serve as benchmark targets.
        modules: Module of every declaration name in the snapshot.
        established: Names that were already present, in the same module,
            in an older snapshot; None when no older snapshot was given.
            Hosted engines index the libraries at different dates, so a
            declaration added recently may be missing from some of them.
            Targets limited to established declarations test search, not
            how recent an index is.
    """

    revision: str
    names: frozenset[str]
    eligible: tuple[Declaration, ...]
    modules: dict[str, str] = field(default_factory=dict)
    established: frozenset[str] | None = None

    def is_established(self, name: str) -> bool:
        """Whether ``name`` may be a target under the established rule."""
        return self.established is None or name in self.established

    def by_name(self) -> dict[str, Declaration]:
        """Map each eligible declaration's name to the declaration."""
        return {declaration.name: declaration for declaration in self.eligible}


def revision_of(label: str, names: Iterable[str]) -> str:
    """Return a revision string: the label plus a hash of the sorted names."""
    digest = hashlib.sha256("\n".join(sorted(names)).encode()).hexdigest()
    return f"leanexplore:{label}:{digest[:16]}"


def _read(path: Path, query: str) -> list[Any]:
    connection = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    try:
        return connection.execute(query).fetchall()
    finally:
        connection.close()


def load_corpus(
    path: Path, label: str | None = None, established: Path | None = None
) -> Corpus:
    """Load a snapshot from ``lean_explore.db``.

    Args:
        path: The SQLite file.
        label: Snapshot label; defaults to the name of the file's directory,
            which is the snapshot version in LeanExplore's cache layout.
        established: An older ``lean_explore.db``. When given, the corpus
            records which declarations it already held in the same module.

    Returns:
        The :class:`Corpus`.
    """
    rows = _read(
        path,
        "SELECT name, module, docstring, source_text, informalization "
        "FROM declarations ORDER BY name",
    )
    older = (
        None
        if established is None
        else set(_read(established, "SELECT name, module FROM declarations"))
    )
    names = frozenset(row[0] for row in rows)
    eligible = tuple(
        declaration
        for declaration in (to_declaration(*row) for row in rows)
        if declaration is not None
    )
    return Corpus(
        revision=revision_of(label or path.resolve().parent.name, names),
        names=names,
        eligible=eligible,
        modules={row[0]: row[1] for row in rows},
        established=(
            None
            if older is None
            else frozenset(row[0] for row in rows if (row[0], row[1]) in older)
        ),
    )


def read_statements(
    path: Path, names: Iterable[str], limit: int = 400
) -> dict[str, str]:
    """Read the start of the source of the named declarations.

    Unlike :attr:`Corpus.eligible`, this covers every declaration of the
    snapshot, including instances and generated ones, which an engine may
    return and a judge then has to read.

    Args:
        path: The SQLite file.
        names: Declaration names to look up; unknown ones are left out.
        limit: Most characters of source text to return for each.
    """
    wanted = sorted(set(names))
    found: dict[str, str] = {}
    connection = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    try:
        for start in range(0, len(wanted), 500):
            chunk = wanted[start : start + 500]
            marks = ",".join("?" for _ in chunk)
            rows = connection.execute(
                f"SELECT name, source_text FROM declarations WHERE name IN ({marks})",
                chunk,
            )
            found.update({name: (text or "").strip()[:limit] for name, text in rows})
    finally:
        connection.close()
    return found
